#!/usr/bin/env python3
"""
Co-op sweep over the story missions of the lobby: each mission started in co-op (host Jak, guest
Daxter), both players voting to skip its intro, then what each player does.

    python scripts/mp-test/mission_sweep.py [mission ...]

For each mission it writes the scenario scripts/mp-test/scenarios/mission-sweep/ (host.txt,
client.txt), runs it with run_mp_test.py, and keeps the result in
out/mp-test/mission-sweep-results/<mission>/: both logs and the screenshots taken 100 s and 120 s
in. Each player's states are traced from the start (trace-play) and logged once in game, then four
times from 100 s on (log-play: state, modes, task managers, turrets). One line per mission goes to
out/mp-test/mission-sweep-results/summary.txt: crashes and each player's last log-play.

Nobody plays: a mission that needs input fails, which is expected. The sweep shows what each
player is put in (a vehicle, a turret, a lizard...), crashes, and what is stuck. The skip votes
(triangle) also get a player out of a vehicle. A run takes about 3 minutes per mission.
"""
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SCENARIO = HERE / "scenarios" / "mission-sweep"
RUN_OUT = ROOT / "out" / "mp-test" / "mission-sweep"
RESULTS = ROOT / "out" / "mp-test" / "mission-sweep-results"

# the missions the lobby offers (play-list entries with a continue point and a name), in story order
MISSIONS = """arena-training-1 arena-fight-1 wascity-chase wascity-pre-game desert-turtle-training
desert-course-race desert-artifact-race-1 wascity-leaper-race desert-hover arena-fight-2 desert-catch-lizards
desert-rescue wascity-gungame arena-fight-3 nest-eggs temple-climb desert-glide volcano-darkeco temple-oracle
desert-oasis-defense temple-tests comb-travel mine-explore mine-blow mine-boss sewer-met-hum city-port-fight
city-port-attack city-gun-course-1 city-sniper-fight sewer-kg-met city-destroy-darkeco forest-kill-plants
city-destroy-grid city-hijack-vehicle city-port-assault city-gun-course-2 city-blow-barricade city-protect-hq
sewer-hum-kg city-power-game desert-artifact-race-2 nest-hunt desert-beast-battle desert-jump-mission
desert-chase-marauders forest-ring-chase factory-sky-battle factory-assault factory-boss temple-defend
wascity-defend forest-turn-on-machine precursor-tour city-blow-tower tower-destroy palace-ruins-patrol
palace-ruins-attack comb-wild-ride precursor-destroy-ship desert-final-boss""".split()

# extra commands per mission, both players: (time, command); the guest runs them 0.5 s later
EXTRA = {
    # Daxter's torpedo: both walk to it, the get-on cutscene skipped
    "city-port-attack": [(102, "goto-type htorpedo"), (104, "press triangle 100"), (107, "press triangle 100"),
                         (111, "press triangle 100"), (115, "press triangle 100")],
}

HOST = """1 trace-play
1 enable
1 name Host
1 color 1
1 character 0
1 mode 1
25 title
26 wait-menu title
28 press down 100
29 press x 100
30 wait-menu mp-lobby-host
31 coop-mission {mission}
63 press x 100
70 wait-player 1
71 log-play
{skips}
100 log-play
101 screenshot a
110 log-play
120 log-play
121 screenshot b
130 log-play
131 log
"""

GUEST_TAIL = """63 log-play
{skips}
100.5 log-play
101.5 screenshot a
110.5 log-play
120.5 log-play
121.5 screenshot b
130.5 log-play
131.5 log
"""


def guest_script() -> str:
    """The challenge scenario's guest up to its join (it joins the lobby), playing Daxter."""
    lines = (HERE / "scenarios" / "challenge" / "client.txt").read_text(encoding="utf-8").splitlines()
    lines = [l for l in lines if l and not l.startswith("#")]
    lines = lines[:lines.index("62 wait-joined") + 1]
    lines = [l.replace("1 character 0", "1 character 1") for l in lines]
    skips = "\n".join(f"{t} press triangle 100" for t in range(74, 98, 3))
    return "1 trace-play\n" + "\n".join(lines) + "\n" + GUEST_TAIL.format(skips=skips)


def ordered(head: str, text: str) -> str:
    """The script lines sorted by time (stable), under a comment: the script runs them in file order."""
    lines = [l for l in text.splitlines() if l.strip()]
    return head + "\n".join(sorted(lines, key=lambda l: float(l.split()[0]))) + "\n"


def main() -> None:
    SCENARIO.mkdir(parents=True, exist_ok=True)
    RESULTS.mkdir(parents=True, exist_ok=True)
    with open(RESULTS / "summary.txt", "a", encoding="utf-8") as summary:
        for mission in sys.argv[1:] or MISSIONS:
            extra = "".join(f"{t} {c}\n" for t, c in EXTRA.get(mission, []))
            extra_guest = "".join(f"{t + 0.5} {c}\n" for t, c in EXTRA.get(mission, []))
            skips = "\n".join(f"{t} press triangle 100" for t in range(73, 97, 3))
            (SCENARIO / "host.txt").write_text(
                ordered(f"# Generated by mission_sweep.py: the host (Jak) starts {mission} in co-op.\n",
                        HOST.format(mission=mission, skips=skips) + extra), encoding="utf-8", newline="\n")
            (SCENARIO / "client.txt").write_text(
                ordered(f"# Generated by mission_sweep.py: the guest (Daxter) joins {mission}.\n",
                        guest_script() + extra_guest), encoding="utf-8", newline="\n")
            started = time.time()
            subprocess.run([sys.executable, str(HERE / "run_mp_test.py"), "mission-sweep"], cwd=ROOT,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=1200)
            keep = RESULTS / mission
            keep.mkdir(exist_ok=True)
            line = [f"{mission} ({time.time() - started:.0f} s)"]
            for side in ("host", "client"):
                log_file = RUN_OUT / side / "gk.log"
                log = log_file.read_text(encoding="utf-8", errors="replace") if log_file.exists() else ""
                (keep / f"{side}.log").write_text(log, encoding="utf-8")
                plays = re.findall(r"\[mp-test\] play state (.*)", log)
                crashes = len(re.findall(r"\] crash: access violation|Assertion failed", log))
                last = plays[-1].strip()[:150] if plays else "-"
                line.append(f"{side}: crash {crashes} plays {len(plays)} last [{last}]")
            shots = RUN_OUT / "screenshots"
            for shot in shots.iterdir() if shots.exists() else []:
                shutil.copy(shot, keep / shot.name)
            summary.write(" | ".join(line) + "\n")
            summary.flush()
            print(line[0], "done")


if __name__ == "__main__":
    main()
